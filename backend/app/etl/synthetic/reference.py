def share(branch: BranchRef, hq_share: float) -> float:
    """Prototip `share()`: HQ — o'z ulushi, stansiyalar — qolgani vazn bo'yicha."""
    if branch.id == HQ_ID:
        return hq_share
    return (1 - hq_share) * branch.weight / WEIGHT_SUM
